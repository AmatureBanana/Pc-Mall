import { expect, test } from '@playwright/test'
import type { Product } from '../src/catalog'

test('storefront cards round score labels returned with two decimal places', async ({ page }) => {
  await page.route('**/api/products', async route => {
    const response = await route.fetch()
    const body: { data: Product[] } = await response.json()
    const memory = body.data.find(product => product.sku === 'KINGSTON-KF560C36BBEK2-32')
    const score = memory?.performanceTags.find(tag => tag.kind === 'SCORE')
    if (!score) throw new Error('Missing memory score in test catalog')
    score.label = '综合评分 47.25分'
    await route.fulfill({ response, json: body })
  })

  await page.goto('/')
  const card = page.getByRole('article').filter({ hasText: '金士顿 FURY Beast' })
  await expect(card.getByText('综合评分 47.3分', { exact: true })).toBeVisible()
})

test('all catalog cards, searched products, details and administration show category-specific performance tags', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/')
  const cards = page.getByRole('article')
  await expect(cards).toHaveCount(13)
  await expect(cards.getByRole('list', { name: '性能标签', exact: true })).toHaveCount(13)
  for (let index = 0; index < 13; index++) {
    await expect(cards.nth(index).getByRole('listitem').first()).toBeVisible()
  }
  await expect(cards.filter({ hasText: 'AMD Ryzen 7 7800X3D' }).getByRole('list')).toContainText('渲染参考 55.3分')
  await expect(cards.filter({ hasText: 'AMD Radeon RX 7800 XT' }).getByRole('list')).toContainText('渲染参考 54.4分')
  const memory = cards.filter({ hasText: '金士顿 FURY Beast' })
  const memoryTag = memory.getByRole('list').getByText('综合评分 47.3分')
  await expect(memoryTag).toBeVisible()
  await expect(memoryTag).toHaveCSS('font-weight', '700')
  const samsung = cards.filter({ hasText: '三星 990 PRO' })
  await expect(samsung.getByRole('list')).toContainText('综合评分 59.7分')
  await expect(cards.filter({ hasText: 'SN850X' }).getByRole('list')).toContainText('综合评分 59.7分')
  await samsung.getByRole('heading').getByRole('link').click()
  const detail = page.getByRole('dialog', { name: '商品详情' })
  await expect(detail.getByText('综合评分 59.7 / 100')).toBeVisible()
  await expect(detail.getByText('性能子分 100.0 / 100', { exact: false })).toBeVisible()
  await expect(detail.getByRole('row', { name: /标称顺序写入/ })).toContainText('6900 MB/s')
  await detail.getByRole('button', { name: '关闭详情' }).click()
  await expect(cards.filter({ hasText: 'RM750e' }).getByRole('list')).toContainText('额定750W')
  await expect(cards.filter({ hasText: 'CC560' }).getByRole('list')).toContainText('显卡限长370mm')
  await expect(cards.filter({ hasText: 'AK400' }).getByRole('list')).toContainText('高度155mm')
  await page.screenshot({ path: '../.local/product-tags-storefront.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('textbox', { name: '搜索商品' }).fill('7800')
  await page.getByRole('button', { name: '搜索', exact: true }).click()
  await expect(cards).toHaveCount(2)
  await expect(cards.getByRole('list', { name: '性能标签', exact: true })).toHaveCount(2)
  const cpu = cards.filter({ hasText: 'AMD Ryzen 7 7800X3D' })
  await cpu.getByRole('heading').getByRole('link').click()
  await expect(detail.getByRole('list', { name: '性能标签', exact: true })).toContainText('渲染参考 55.3分')
  await expect(detail.getByRole('list', { name: '性能标签', exact: true }).getByRole('link').first()).toHaveAttribute('href', /opendata\.blender\.org/)
  await detail.getByRole('button', { name: '关闭详情' }).click()
  await page.goto('/#login')
  const login = page.getByRole('dialog', { name: '统一登录' })
  await login.getByLabel('用户名', { exact: true }).fill(process.env.BROWSER_ADMIN_USERNAME!)
  await login.getByLabel('密码', { exact: true }).fill(process.env.BROWSER_ADMIN_PASSWORD!)
  await login.getByRole('button', { name: '登录', exact: true }).click()
  const admin = page.getByRole('dialog', { name: '管理后台' })
  await expect(admin).toBeVisible()
  await admin.getByRole('navigation').getByRole('button', { name: '商品管理' }).click()
  await admin.getByLabel('商品关键词').fill('KINGSTON-KF560C36BBEK2-32')
  await admin.getByRole('button', { name: '查询', exact: true }).click()
  await expect(admin.getByRole('row').filter({ hasText: '金士顿 FURY Beast' }).getByRole('list', { name: '性能标签', exact: true })).toContainText('综合评分 47.3分')
  await admin.getByRole('button', { name: '查看编辑' }).click()
  await expect(admin.getByRole('list', { name: '性能标签', exact: true })).toContainText('综合评分 47.3分')
  await expect(admin.getByRole('spinbutton', { name: 'CAS 延迟（CL） · 周期', exact: true })).toHaveValue('36')
  await expect(admin.getByRole('region', { name: '性能评分维护' })).toHaveCount(0)
  await admin.getByRole('heading', { name: '性能标签', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: '../.local/product-tags-administration.png', fullPage: true, animations: 'disabled' })
})
