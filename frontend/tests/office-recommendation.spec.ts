import { expect, test } from '@playwright/test'

test('task21: office budget creates a real scored plan and imports all selections to DIY', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '办公推荐 · 开始推荐' }).click()
  const dialog = page.getByRole('dialog', { name: '办公推荐', exact: true })
  await dialog.getByLabel('预算（CNY）').fill('10000')
  await dialog.getByRole('button', { name: '生成办公方案', exact: true }).click()
  const result = dialog.getByRole('region', { name: '办公推荐方案' })
  await expect(result).toContainText('办公评分')
  await expect(result).toContainText('/ 100')
  await expect(result.getByRole('link')).toHaveCount(7)
  const scoreText = await result.locator('.recommendation-score .score-display strong').innerText()
  await page.screenshot({ path: '../docs/evidence/task21-office-result.png', fullPage: true, animations: 'disabled' })
  await result.getByRole('button', { name: '转入 DIY 调整', exact: true }).click()
  await expect(page).toHaveURL(/#diy$/)
  const summary = page.getByRole('region', { name: '性能评分', exact: true })
  await expect(summary.locator('.score-display strong')).toHaveText(scoreText)
  await expect(summary.getByRole('meter', { name: '性能评分' })).toBeVisible()
  await expect(summary).not.toContainText('办公评分')
  const saved = await page.evaluate(() => JSON.parse(sessionStorage.getItem('pc-mall.diy.workspace.v1')!))
  expect(saved.selections).toHaveLength(7)
  expect(saved.integratedGraphicsCpuId).toBeGreaterThan(0)
  expect(saved.memoryQuantity).toBe(2)
  expect(saved.selections.every((item: { source: string }) => item.source === 'RECOMMENDATION')).toBe(true)
  await expect(page.getByRole('region', { name: '当前配置' }).getByText('核心检测通过', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: 'DIY 硬件分类' }).getByRole('button', { name: /^内存 / }).click()
  await page.getByRole('button', { name: '增加内存数量' }).click()
  await expect(page.getByRole('status').filter({ hasText: '旧推荐评分与解释已失效' })).toBeVisible()
  await expect(summary.getByRole('meter', { name: '性能评分' })).toBeVisible()
  await page.reload()
  expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('pc-mall.diy.workspace.v1')!).selections)).toEqual(saved.selections)
})

test('invalid budgets do not request recommendations and a proven budget failure remains editable', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => { if (request.url().endsWith('/api/recommendations')) requests.push(request.postData()!) })
  await page.goto('/')
  await page.getByRole('button', { name: '办公推荐 · 开始推荐' }).click()
  const dialog = page.getByRole('dialog', { name: '办公推荐', exact: true })
  for (const value of ['0', '-1', 'abc', '12.345']) {
    await dialog.getByLabel('预算（CNY）').fill(value)
    await dialog.getByRole('button', { name: '生成办公方案', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('请输入')
  }
  expect(requests).toEqual([])
  await dialog.getByLabel('预算（CNY）').fill('1')
  await dialog.getByRole('button', { name: '生成办公方案', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('价格下界')
  await expect(dialog.getByRole('button', { name: '转入 DIY 调整' })).toHaveCount(0)
})

