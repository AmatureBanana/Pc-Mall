test('task21: an old recommendation cannot reappear after the budget is edited', async ({ page }) => {
  let release!: () => void
  let captured!: () => void
  let delivered!: () => void
  const pending = new Promise<void>(resolve => { release = resolve })
  const ready = new Promise<void>(resolve => { captured = resolve })
  const finished = new Promise<void>(resolve => { delivered = resolve })
  await page.route('**/api/recommendations', async route => {
    const response = await route.fetch()
    captured()
    await pending
    await route.fulfill({ response }).catch(() => {})
    delivered()
  })
  await page.goto('/')
  await page.getByRole('button', { name: '办公推荐 · 开始推荐' }).click()
  const dialog = page.getByRole('dialog', { name: '办公推荐', exact: true })
  await dialog.getByLabel('预算（CNY）').fill('10000')
  await dialog.getByRole('button', { name: '生成办公方案', exact: true }).click()
  await ready
  await dialog.getByLabel('预算（CNY）').fill('9000')
  release()
  await finished
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await expect(dialog.getByRole('region', { name: '办公推荐方案' })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: '生成办公方案' })).toBeEnabled()
})

test('task21: a real office result remains readable and its DIY action reachable on mobile', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '办公推荐 · 开始推荐' }).click()
  const dialog = page.getByRole('dialog', { name: '办公推荐', exact: true })
  await dialog.getByLabel('预算（CNY）').fill('10000')
  await dialog.getByRole('button', { name: '生成办公方案', exact: true }).click()
  await expect(dialog.getByRole('region', { name: '办公推荐方案' })).toContainText('办公评分')
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const transfer = dialog.getByRole('button', { name: '转入 DIY 调整' })
  await transfer.scrollIntoViewIfNeeded()
  await expect(transfer).toBeInViewport()
  await page.screenshot({ path: '../docs/evidence/task21-office-mobile.png', fullPage: true, animations: 'disabled' })
})
