import { expect, test } from '@playwright/test'

test('CPU integrated graphics stays first, replaces a discrete card for free and restores on reload', async ({ page, request }) => {
  await page.goto('/#diy')
  await page.getByRole('button', { name: '选择 Intel Core i5-14600K', exact: true }).click()
  const categories = page.getByRole('navigation', { name: 'DIY 硬件分类' })
  const configuration = page.getByRole('region', { name: '当前配置' })
  await categories.getByRole('button', { name: /^显卡 / }).click()
  const integrated = page.getByRole('article', { name: 'CPU 核显候选' })
  await expect(integrated).toContainText('Intel UHD Graphics 770')
  await expect(integrated).toContainText('渲染参考待核验')
  await expect(page.locator('.diy-candidate-list > article').first()).toHaveAttribute('aria-label', 'CPU 核显候选')
  await page.getByLabel('候选商品排序').selectOption('price-desc')
  await page.getByRole('button', { name: 'AMD', exact: true }).click()
  await expect(page.locator('.diy-candidate-list > article').first()).toHaveAttribute('aria-label', 'CPU 核显候选')
  await page.getByRole('button', { name: '全部', exact: true }).click()
  await page.getByRole('button', { name: '选择 NVIDIA GeForce RTX 4070 SUPER', exact: true }).click()
  await expect(configuration.getByLabel('当前参考总价')).toHaveText('¥6,598.00')
  await page.getByRole('button', { name: '选择 CPU 核显', exact: true }).click()
  await expect(configuration.getByLabel('当前参考总价')).toHaveText('¥1,599.00')
  await expect(configuration).toContainText('核显 · Intel UHD Graphics 770')
  const state = await page.evaluate(() => JSON.parse(sessionStorage.getItem('pc-mall.diy.workspace.v1')!))
  expect(state.selections).toHaveLength(1)
  expect(state.selections[0].category).toBe('CPU')
  expect(state.integratedGraphicsCpuId).toBe(state.selections[0].productId)
  await page.reload()
  await expect(configuration).toContainText('核显 · Intel UHD Graphics 770')
  await categories.getByRole('button', { name: /^显卡 / }).click()
  await page.screenshot({ path: '../docs/evidence/diy-integrated-graphics.png', fullPage: true, animations: 'disabled' })
  await integrated.getByText('核显规格与支持能力').click()
  await expect(integrated).toContainText('32')
  await page.screenshot({ path: '../docs/evidence/diy-integrated-graphics-specs.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect((await integrated.locator('dd').first().boundingBox())!.width).toBeGreaterThan(100)
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: '../docs/evidence/diy-integrated-graphics-mobile.png', fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 1586, height: 992 })
  await configuration.getByRole('button', { name: '移除 显卡', exact: true }).click()
  await expect(configuration.getByRole('button', { name: /^显卡 / })).toContainText('未选择')
  await page.getByRole('button', { name: '选择 CPU 核显', exact: true }).click()
  await page.getByRole('button', { name: '选择 NVIDIA GeForce RTX 4070 SUPER', exact: true }).click()
  expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('pc-mall.diy.workspace.v1')!).integratedGraphicsCpuId)).toBeUndefined()
  const gpuProducts = (await (await request.get('/api/products?category=GPU')).json()).data
  expect(gpuProducts.every((product: { name: string }) => !/UHD|核显|Radeon Graphics$/.test(product.name))).toBe(true)
})

test('changing or removing the CPU clears its integrated choice and unsupported CPUs have no card', async ({ page }) => {
  await page.goto('/#diy')
  const categories = page.getByRole('navigation', { name: 'DIY 硬件分类' })
  const configuration = page.getByRole('region', { name: '当前配置' })
  const integrated = page.getByRole('article', { name: 'CPU 核显候选' })
  await categories.getByRole('button', { name: /^显卡 / }).click()
  await expect(integrated).toHaveCount(0)
  await categories.getByRole('button', { name: /^CPU / }).click()
  await page.getByRole('button', { name: '选择 AMD Ryzen 7 7800X3D', exact: true }).click()
  await categories.getByRole('button', { name: /^显卡 / }).click()
  await expect(integrated).toContainText('AMD Radeon Graphics')
  await page.getByRole('button', { name: '选择 CPU 核显', exact: true }).click()
  await configuration.getByRole('button', { name: '替换 CPU', exact: true }).click()
  await page.getByRole('button', { name: '选择 Intel Core i5-14600KF', exact: true }).click()
  await categories.getByRole('button', { name: /^显卡 / }).click()
  await expect(integrated).toHaveCount(0)
  await expect(configuration.getByRole('button', { name: /^显卡 / })).toContainText('未选择')
  expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('pc-mall.diy.workspace.v1')!).integratedGraphicsCpuId)).toBeUndefined()
  await configuration.getByRole('button', { name: '移除 CPU', exact: true }).click()
  await expect(integrated).toHaveCount(0)
})

test('an unavailable CPU detail keeps a saved integrated choice removable without inventing specifications', async ({ page }) => {
  await page.goto('/#diy')
  await page.getByRole('button', { name: '选择 Intel Core i5-14600K', exact: true }).click()
  await page.getByRole('navigation', { name: 'DIY 硬件分类' }).getByRole('button', { name: /^显卡 / }).click()
  await page.getByRole('button', { name: '选择 CPU 核显', exact: true }).click()
  await page.route(/\/api\/products\/\d+$/, route => route.fulfill({ status: 503, json: { code: 'CATALOG_UNAVAILABLE' } }))
  await page.reload()
  const configuration = page.getByRole('region', { name: '当前配置' })
  await expect(configuration).toContainText('核显 · 参数待重验')
  await configuration.getByRole('button', { name: '移除 显卡', exact: true }).click()
  await expect(configuration.getByRole('button', { name: /^显卡 / })).toContainText('未选择')
})
